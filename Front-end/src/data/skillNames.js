const ROMAN = ["", "I", "II", "III", "IV", "V", "VI", "VII", "VIII", "IX"];

export function characterRanks() {
  const ranks = [{ id: "Norank", label: "랭크 없음" }];
  const push = (id, name) => {
    ranks.push({ id, label: name });
  };
  const triples = [
    ["Blackiron", "견습"],
    ["Bronze", "정예"],
    ["Silver", "숙련"],
    ["Gold", "챔피언"],
    ["Saint", "대가"],
    ["Legend", "귀감"],
    ["Angel", "성자"],
  ];
  for (const [id, name] of triples) {
    for (let step = 1; step <= 3; step += 1) push(`${id}${step}`, `${name} ${ROMAN[step]}`);
  }
  for (const [id, name] of [["Godtouched", "영체"], ["Demigod", "초월"]]) {
    let step = 1;
    for (let stage = 1; stage <= 3; stage += 1) {
      for (let sub = 1; sub <= 3; sub += 1) {
        push(`${id}${stage}_${sub}`, `${name} ${ROMAN[step]}`);
        step += 1;
      }
    }
  }
  return ranks;
}
